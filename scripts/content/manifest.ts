import { dirname, relative } from "node:path";
import type { ExperienceEntryDetail, ProjectDetail } from "../../src/types/content.ts";
import { heroSourcePlaceholder } from "./projects.ts";
import type { ParsedProject } from "./types.ts";
import type { SiteContent, SiteMetadataContent } from "../../src/types/site.ts";

function heroIdentifier(slug: string): string {
  const camel = slug.replace(/-([a-z0-9])/g, (_, character: string) => character.toUpperCase());
  return `${camel}Hero`;
}

function relativeImportTarget(manifestPath: string, sourcePath: string): string {
  const target = relative(dirname(manifestPath), sourcePath).split("\\").join("/");
  return target.startsWith(".") ? target : `./${target}`;
}

export function renderManifest(
  projects: ParsedProject[],
  experience: ExperienceEntryDetail[],
  manifestPath: string,
  site: SiteContent,
  metadata: SiteMetadataContent,
): string {
  const imports = projects.map(
    (project) =>
      `import ${heroIdentifier(project.detail.slug)} from "${relativeImportTarget(manifestPath, project.heroSourcePath)}";`,
  );

  const records = projects.map((project) => {
    const identifier = heroIdentifier(project.detail.slug);
    const detail: ProjectDetail = {
      ...project.detail,
      hero: { ...project.detail.hero, src: heroSourcePlaceholder },
    };
    return JSON.stringify(detail, null, 2).replace(
      `"${heroSourcePlaceholder}"`,
      identifier,
    );
  });

  const importBlock = imports.length > 0 ? `${imports.join("\n")}\n` : "";
  const recordBlock = records.length > 0 ? `[\n${records.join(",\n")},\n]` : "[]";
  const experienceBlock =
    experience.length > 0
      ? `[\n${experience.map((entry) => JSON.stringify(entry, null, 2)).join(",\n")},\n]`
      : "[]";

  return `// Generated by scripts/build-content.ts. Do not edit manually.
${importBlock}import type { ExperienceEntryDetail, ProjectDetail } from "../types/content.ts";
import type { SiteContent, SiteMetadataContent } from "../types/site.ts";

export const site = ${JSON.stringify(site, null, 2)} satisfies SiteContent;

export const siteMetadata = ${JSON.stringify(metadata, null, 2)} satisfies SiteMetadataContent;

const projectRecords = ${recordBlock} satisfies ProjectDetail[];

const experienceRecords = ${experienceBlock} satisfies ExperienceEntryDetail[];

export const projects: ProjectDetail[] = projectRecords;

export const experience: ExperienceEntryDetail[] = experienceRecords;

export function findProject(slug: string): ProjectDetail | undefined {
  return projects.find((project) => project.slug === slug);
}
`;
}
